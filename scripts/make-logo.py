# Draws the Ntoma mark: a basket-weave square (like woven cloth) turned inside a ring.
# Writes public/icon.svg and src/components/logo-mark.ts. Re-run after changing the numbers.
cell, bar_w, bar_len, gap = 30, 8.5, 24, 4.5
bars = []
off = -2 * cell
for r in range(4):
    for c in range(4):
        x0, y0 = off + c * cell, off + r * cell
        horiz = (r + c) % 2 == 0
        for k in (0, 1):
            if horiz:
                x = x0 + (cell - bar_len) / 2
                y = y0 + cell / 2 - bar_w - gap / 2 + k * (bar_w + gap)
                bars.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{bar_len}" height="{bar_w}" rx="3"/>')
            else:
                y = y0 + (cell - bar_len) / 2
                x = x0 + cell / 2 - bar_w - gap / 2 + k * (bar_w + gap)
                bars.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{bar_w}" height="{bar_len}" rx="3"/>')
inner = (
    '<circle cx="128" cy="128" r="110" fill="none" stroke="currentColor" stroke-width="9"/>'
    f'<g fill="currentColor" transform="translate(128 128) rotate(-30)">{"".join(bars)}</g>'
)
GREEN = "#14382a"
with open("public/icon.svg", "w") as f:
    f.write(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">\n'
        '  <rect width="256" height="256" rx="56" fill="#ffffff"/>\n'
        f'  <g color="{GREEN}" transform="translate(128 128) scale(0.8) translate(-128 -128)">{inner}</g>\n'
        "</svg>\n"
    )
with open("src/components/logo-mark.ts", "w") as f:
    f.write("// Generated by scripts/make-logo.py. Inner SVG of the Ntoma mark on a 256x256 viewBox, drawn in currentColor.\n")
    f.write(f"export const LOGO_MARK = `{inner}`;\n")
