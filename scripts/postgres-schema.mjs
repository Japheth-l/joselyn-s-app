// Production uses PostgreSQL while local development uses a SQLite file.
// Prisma can't switch providers with an environment variable, so this writes a
// Postgres copy of prisma/schema.prisma for deployments to build against.
import { readFileSync, writeFileSync } from "fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (out === src) throw new Error('Expected provider = "sqlite" in prisma/schema.prisma');
writeFileSync("prisma/schema.postgres.prisma", "// Generated by scripts/postgres-schema.mjs. Do not edit.\n" + out);
console.log("Wrote prisma/schema.postgres.prisma");
